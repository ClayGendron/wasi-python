"""Write spec 100's drafting prototype of recipes/numpy_lapack_shims.c from the argument counts
read from OpenBLAS (sigs.sh). The builder writes the real file by hand with numpy's typed
prototypes; this one only proves the ABI: every argument is a pointer (i32)."""

import sys

# name: (argument count, OpenBLAS's return): from sigs.sh's output
SIGS = {}
for line in open(sys.argv[1]):
    obj, rest = line.split(" ", 1)
    if not obj.endswith(".o"):
        continue
    args, ret = rest.strip().split(" -> ")
    SIGS[obj[:-2]] = (args.count("i32"), ret)

out = ["/* generated by make_shims.py: the ABI prototype of recipes/numpy_lapack_shims.c */"]
for name, (n, ret) in sorted(SIGS.items()):
    if name == "xerbla":
        continue  # numpy's python_xerbla takes its prefixed name; OpenBLAS keeps xerbla_
    params = ", ".join(f"void *a{i}" for i in range(n))
    argv = ", ".join(f"a{i}" for i in range(n))
    if name in ("cdotc", "cdotu", "zdotc", "zdotu"):  # numpy declares these void, as OpenBLAS defines them
        out.append(f"void {name}_({params});")
        out.append(f"void wasi_numpy_{name}_({params}) {{ {name}_({argv}); }}")
    elif ret == "void":
        out.append(f"void {name}_({params});")
        out.append(f"int wasi_numpy_{name}_({params}) {{ {name}_({argv}); return 0; }}")
    else:
        ctype = {"f32": "float", "f64": "double"}[ret]
        out.append(f"{ctype} {name}_({params});")
        out.append(f"{ctype} wasi_numpy_{name}_({params}) {{ return {name}_({argv}); }}")
print("\n".join(out))
