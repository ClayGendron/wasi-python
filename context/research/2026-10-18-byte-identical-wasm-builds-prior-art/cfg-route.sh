#!/bin/sh
# Spec 059, Decisions 1 and 10: the configuration-file route, reproduced from the repository.
#
#   sh context/research/2026-10-18-byte-identical-wasm-builds-prior-art/cfg-route.sh <scratch> <x86_64 sdk tarball>
#
# Unpacks the pinned arm64 macOS SDK (from downloads/) and the pinned x86_64 Linux SDK (the given
# tarball, checked against downloads/SHA256SUMS) into <scratch>, appends -ffp-contract=off to each
# tree's bin/clang.cfg and bin/clang++.cfg exactly as step 10 does, and records, as text under
# outputs/cfg-route/: which configuration file each driver reads; the -cc1 line of clang, clang -E
# and clang++ (-###); clang-cpp reading no file; a hello-world compiled, linked and compiled-and-
# linked under -Werror -Wunused-command-line-argument; the predefined macros with and without the
# flag; the override family, each member's effect on the -cc1 line; the constant-fold case (the
# pre-build review's F2); the pragma case (F5); and the numpy object through the edited files on
# both hosts. The x86_64 SDK runs in the research container (linux/amd64; under Rosetta on Apple
# silicon). The numpy file is regenerated by decision1-host.sh (2026-10-17-the-x86-64-rebuild/);
# pass its folder as the third argument to include that fact, else it is skipped.
set -eu
HERE=$(CDPATH= cd "$(dirname "$0")/../../.." && pwd -P)
SCRATCH=$1
X86_TGZ=$2
NPY=${3:-}
OUT="$HERE/context/research/2026-10-18-byte-identical-wasm-builds-prior-art/outputs/cfg-route"
IMG=debian:trixie-slim@sha256:a29215f6a35e51e22adffa17f89e9d2ef06214e64a2bad10d765c46aea49f11f
mkdir -p "$SCRATCH" "$OUT"
SCRATCH=$(CDPATH= cd "$SCRATCH" && pwd -P)
MAC_TGZ="$HERE/downloads/wasi-sdk-33.0-arm64-macos.tar.gz"
for f in "$MAC_TGZ" "$X86_TGZ"; do
  grep "  $(basename "$f")\$" "$HERE/downloads/SHA256SUMS" > "$SCRATCH/pin.txt"
  (cd "$(dirname "$f")" && shasum -a 256 -c "$SCRATCH/pin.txt") || { echo "$f does not match its pin" >&2; exit 1; }
done
rm -rf "$SCRATCH/mac" "$SCRATCH/x86" "$SCRATCH/src"
mkdir -p "$SCRATCH/mac" "$SCRATCH/x86" "$SCRATCH/src"
tar -xzf "$MAC_TGZ" -C "$SCRATCH/mac"
tar -xzf "$X86_TGZ" -C "$SCRATCH/x86"
MAC="$SCRATCH/mac/wasi-sdk-33.0-arm64-macos"
X86="$SCRATCH/x86/wasi-sdk-33.0-x86_64-linux"
edit() { # an SDK tree: what step 10's contract_off does
  for cfg in clang.cfg clang++.cfg; do
    f="$1/bin/$cfg"
    [ -z "$(tail -c 1 "$f")" ] || printf '\n' >> "$f"
    printf '%s\n' "-ffp-contract=off" >> "$f"
  done
}
cp "$HERE/context/upstream/4-llvm-wasm-isel-slot-order/evidence/slot-order.c" "$SCRATCH/src/"
printf '#include <stdio.h>\nint main(void) { puts("hi"); return 0; }\n' > "$SCRATCH/src/hello.c"
printf 'static double g(double a, double b, double c) { return a * b + c; }\ndouble h(void) { return g(0.1, 10.0, -1.0); }\n' > "$SCRATCH/src/fold.c"
printf '#pragma STDC FP_CONTRACT ON\ndouble f(double a, double b, double c) { return a * b + c; }\n' > "$SCRATCH/src/pragma.c"
[ -n "$NPY" ] && cp "$NPY/npy_math_complex.i" "$SCRATCH/src/"
F="--target=wasm32-wasip1 -std=c11 -O3 -fno-strict-aliasing -ftrapping-math -fvisibility=hidden -w"
H16() { shasum -a 256 "$1" | cut -c1-16; }

# 1. Before the edit: the default's objects (the memo's pair).
{
  echo "slot-order.c default: aarch64 $("$MAC/bin/clang" $F -c "$SCRATCH/src/slot-order.c" -o "$SCRATCH/a.o" && H16 "$SCRATCH/a.o")"
  "$MAC/bin/clang" --target=wasm32-wasip1 -dM -E "$SCRATCH/src/hello.c" > "$SCRATCH/macros-before.txt"
} > "$OUT/before.txt" 2>&1
edit "$MAC"
edit "$X86"
{
  echo "== clang.cfg"; cat "$MAC/bin/clang.cfg"; echo "== clang++.cfg"; cat "$MAC/bin/clang++.cfg"
} > "$OUT/cfg-files.txt"
# 2. Which file each driver reads, and the -cc1 lines.
{
  for d in clang clang++ clang-cpp; do
    echo "== $d -v"; "$MAC/bin/$d" --target=wasm32-wasip1 -v -E "$SCRATCH/src/hello.c" 2>&1 >/dev/null | grep -E 'Configuration file|^ "' | sed 's/^\( "[^"]*" "-cc1"\).*\(-ffp-contract=[a-z]*\).*/\1 ... \2 .../' || true
  done
  echo "== clang -### -c"; "$MAC/bin/clang" --target=wasm32-wasip1 -### -c "$SCRATCH/src/hello.c" 2>&1 | grep -o -- '"-ffp-contract=[a-z]*"' | sort | uniq -c
  echo "== clang -### -E"; "$MAC/bin/clang" --target=wasm32-wasip1 -### -E "$SCRATCH/src/hello.c" 2>&1 | grep -o -- '"-ffp-contract=[a-z]*"' | sort | uniq -c
  echo "== clang++ -### -c -x c++"; "$MAC/bin/clang++" --target=wasm32-wasip1 -### -c -x c++ "$SCRATCH/src/hello.c" 2>&1 | grep -o -- '"-ffp-contract=[a-z]*"' | sort | uniq -c
  echo "== clang-cpp -### (no file read)"; "$MAC/bin/clang-cpp" -### "$SCRATCH/src/hello.c" 2>&1 | grep -o -- '"-ffp-contract=[a-z]*"\|Configuration file.*' | sort | uniq -c
} > "$OUT/drivers.txt" 2>&1
# 3. -Werror: compile, link, compile-and-link, -E, -M, -fsyntax-only.
{
  W="-Werror -Wunused-command-line-argument"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W -c "$SCRATCH/src/hello.c" -o "$SCRATCH/hello.o" && echo "compile: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W "$SCRATCH/hello.o" -o "$SCRATCH/hello.wasm" && echo "link: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W "$SCRATCH/src/hello.c" -o "$SCRATCH/hello2.wasm" && echo "compile-and-link: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W -E "$SCRATCH/src/hello.c" > /dev/null && echo "-E: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W -M "$SCRATCH/src/hello.c" > /dev/null && echo "-M: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 $W -fsyntax-only "$SCRATCH/src/hello.c" && echo "-fsyntax-only: ok"
  "$MAC/bin/clang" --target=wasm32-wasip1 -dM -E "$SCRATCH/src/hello.c" > "$SCRATCH/macros-after.txt"
  cmp "$SCRATCH/macros-before.txt" "$SCRATCH/macros-after.txt" && echo "predefined macros: equal with and without the flag ($(wc -l < "$SCRATCH/macros-after.txt" | tr -d ' ') lines)"
} > "$OUT/werror.txt" 2>&1
# 4. The override family, each member's -cc1 value through the edited file.
{
  for o in "" -ffp-contract=on -ffp-contract=fast -ffp-model=precise -ffp-model=fast -ffast-math -Ofast -funsafe-math-optimizations --no-default-config; do
    v=$("$MAC/bin/clang" --target=wasm32-wasip1 -### -c $o "$SCRATCH/src/hello.c" 2>&1 | grep -o -- '"-ffp-contract=[a-z]*"' | tr '\n' ' ')
    printf '%-32s -> %s\n' "${o:-(none)}" "${v:-no -ffp-contract on the -cc1 line}"
  done
} > "$OUT/overrides.txt" 2>&1
# 5. The objects through the edited files, both hosts; the fold; the pragma.
X="docker run --rm --platform linux/amd64 -v $SCRATCH/x86:/sdk:ro -v $SCRATCH/src:/r -w /r $IMG /sdk/wasi-sdk-33.0-x86_64-linux/bin/clang"
{
  echo "slot-order.c through the file: aarch64 $("$MAC/bin/clang" $F -c "$SCRATCH/src/slot-order.c" -o "$SCRATCH/a.o" && H16 "$SCRATCH/a.o"), x86_64 $($X $F -c slot-order.c -o x.o && H16 "$SCRATCH/src/x.o")"
  echo "slot-order.c with -ffp-contract=on after the file: aarch64 $("$MAC/bin/clang" $F -ffp-contract=on -c "$SCRATCH/src/slot-order.c" -o "$SCRATCH/a.o" && H16 "$SCRATCH/a.o")"
  echo "slot-order.c with -ffp-model=precise after the file: aarch64 $("$MAC/bin/clang" $F -ffp-model=precise -c "$SCRATCH/src/slot-order.c" -o "$SCRATCH/a.o" && H16 "$SCRATCH/a.o"), x86_64 $($X $F -ffp-model=precise -c slot-order.c -o x.o && H16 "$SCRATCH/src/x.o")"
  if [ -f "$SCRATCH/src/npy_math_complex.i" ]; then
    N="--target=wasm32-wasip1 -std=c11 -O3 -fno-strict-aliasing -ftrapping-math -fvisibility=hidden -Wno-unsupported-floating-point-opt -w"
    echo "npy_math_complex.i ($(wc -c < "$SCRATCH/src/npy_math_complex.i" | tr -d ' ') bytes, $(H16 "$SCRATCH/src/npy_math_complex.i")) through the file: aarch64 $("$MAC/bin/clang" $N -c "$SCRATCH/src/npy_math_complex.i" -o "$SCRATCH/n.o" && H16 "$SCRATCH/n.o"), x86_64 $($X $N -c npy_math_complex.i -o nx.o && H16 "$SCRATCH/src/nx.o")"
  else
    echo "npy_math_complex.i: not given (run decision1-host.sh first)"
  fi
  echo "== fold.c at -O2: h() under the default, then through the file"
  "$MAC/bin/clang" --target=wasm32-wasip1 -O2 -ffp-contract=on -S -emit-llvm "$SCRATCH/src/fold.c" -o - | grep -E 'ret double' | sed 's/^/  default: /'
  "$MAC/bin/clang" --target=wasm32-wasip1 -O2 -S -emit-llvm "$SCRATCH/src/fold.c" -o - | grep -E 'ret double' | sed 's/^/  file:    /'
  echo "== pragma.c through the file: fmuladd calls in the IR"
  "$MAC/bin/clang" --target=wasm32-wasip1 -O2 -S -emit-llvm "$SCRATCH/src/pragma.c" -o - | grep -c 'llvm.fmuladd' || true
} > "$OUT/objects.txt" 2>&1
cat "$OUT"/drivers.txt "$OUT"/werror.txt "$OUT"/overrides.txt "$OUT"/objects.txt
