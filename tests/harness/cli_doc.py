"""The command's reference page, rendered from its parser.

    uv run python tests/harness/cli_doc.py --write   # rewrite the block in docs/reference/cli.md
    uv run python tests/harness/cli_doc.py --check   # exit 1 if it differs from the live parser

The page's block is a section per command, `wasi-python run` and then `wasi-python packages`,
each a table of its options: each option, its value, its default and one sentence. The sentence
is the option's `help=`, the text `--help` prints, and the render fails on an option that has
none, so the page and the parser cannot drift apart. Importing
`wasi_python.cli` never loads wasmtime.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PAGE = REPO / "docs" / "reference" / "cli.md"
BEGIN = "<!-- cli reference: begin (generated by tests/harness/cli_doc.py) -->"
END = "<!-- cli reference: end -->"
WRITE = "uv run python tests/harness/cli_doc.py --write"


def live_parser() -> argparse.ArgumentParser:
    """`wasi-python run`'s own parser."""
    from wasi_python import cli

    return cli._parser()


def live_parsers() -> tuple[argparse.ArgumentParser, ...]:
    """Each command's own parser, in the page's order."""
    from wasi_python import cli

    return (cli._parser(), cli._packages_parser())


def live_block() -> str:
    """The page's block: a section per command, rendered from its live parser."""
    return "\n\n".join(render(p) for p in live_parsers())


def _default(action: argparse.Action) -> str:
    if action.default is argparse.SUPPRESS:
        return "`run`'s default"
    if action.default is False and action.nargs == 0:
        return "off"
    if action.default in (None, []):
        return "none"
    return f"`{action.default}`"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render(parser: argparse.ArgumentParser) -> str:
    """The block for one parser: its name, description and usage, a row per option in the
    parser's order (the help option left out), and a line per group of options that exclude
    each other. ValueError names every option that has no help."""
    # From Python 3.14 argparse colours its usage line under a terminal or FORCE_COLOR; the page
    # must be the same text wherever it is rendered, so colour is off (older parsers have none).
    if hasattr(parser, "color"):
        parser.color = False
    actions = [a for a in parser._actions if a.option_strings and a.dest != "help"]
    errors = []
    rows = []
    for a in actions:
        name = a.option_strings[-1]
        if a.help in (None, argparse.SUPPRESS):
            errors.append(f"{name}: no help; give it help= in the parser")
        text = "" if a.help in (None, argparse.SUPPRESS) else str(a.help)
        if isinstance(a, argparse._AppendAction):
            text += " (repeatable)"
        value = f"`{a.metavar}`" if a.metavar else ""
        rows.append(f"| `{name}` | {value} | {_default(a)} | {_cell(text)} |")
    if errors:
        raise ValueError("; ".join(errors))
    lines = [f"### `{parser.prog}`", ""]
    if parser.description:
        lines += [parser.description, ""]
    lines += ["```", parser.format_usage().removeprefix("usage: ").strip(), "```", ""]
    lines += ["| option | value | default | description |", "|---|---|---|---|", *rows]
    for group in parser._mutually_exclusive_groups:
        opts = [f"`{a.option_strings[-1]}`" for a in group._group_actions]
        listed = ", ".join(opts[:-1]) + f" and {opts[-1]}"
        lines += ["", f"At most one of {listed}."]
    return "\n".join(lines)


def _plain(text: str) -> str:
    """The text with every fenced block's lines blanked, so a marker shown as an example is
    never the block."""
    out, fence = [], None
    for line in text.split("\n"):
        m = re.match(r"\s*(`{3,}|~{3,})", line)
        if fence is None and m:
            fence = m[1]
            out.append("")
        elif fence is not None:
            if line.strip().startswith(fence):
                fence = None
            out.append("")
        else:
            out.append(line)
    return "\n".join(out)


def page_block(text: str) -> tuple[int, str | None]:
    """(how many blocks, the one block's content, its blank edges dropped) between the markers,
    fences ignored."""
    lines = _plain(text).split("\n")
    begins = [i for i, line in enumerate(lines) if line.strip() == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == END]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        return max(len(begins), len(ends)), None
    original = text.split("\n")
    return 1, "\n".join(original[begins[0] + 1 : ends[0]]).strip("\n")


def replace_block(text: str, block: str) -> str:
    """The page with its one block's content replaced; the caller checks there is one."""
    before, rest = text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return before + BEGIN + "\n\n" + block.strip("\n") + "\n\n" + END + after


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    p.add_argument("--page", type=Path, default=PAGE)
    ns = p.parse_args(argv)
    block = live_block()
    text = ns.page.read_text(encoding="utf-8") if ns.page.is_file() else ""
    count, current = page_block(text)
    if count != 1:
        print(f"{ns.page}: needs exactly one pair of markers ({BEGIN} … {END})")
        return 1
    if ns.write:
        with ns.page.open("w", encoding="utf-8", newline="\n") as f:
            f.write(replace_block(text, block))
        return 0
    if current != block:
        print(f"{ns.page}: the command's reference differs from its parser; run {WRITE}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
