def command_facts(cli: Any, runner: Any) -> dict[str, Any]:
    import tomllib

    scripts = tomllib.loads((REPO / "pyproject.toml").read_text(encoding="utf-8"))["project"][
        "scripts"
    ]
    parser = cli._parser()
    names = {parser._registry_get("action", k): k for k in ("store", "append", "store_true")}
    names[cli._Once] = "once"
    options = []
    for a in parser._actions:
        if not a.option_strings or a.option_strings == ["-h", "--help"]:
            continue
        if type(a) not in names:
            raise AssertionError(f"{a.option_strings}: an action the render does not name")
        options.append([max(a.option_strings, key=len), a.metavar, names[type(a)]])

    results: list[Any] = [
        runner.Completed(exit_code=0, stdout=b"1\n", stderr=b"", trapped=None, fuel_used=None),
        runner.Completed(exit_code=0, stdout=b"\xff", stderr=b"\xff", trapped=None, fuel_used=None),
        ValueError("a stand-in failure"),
        KeyboardInterrupt(),
    ]
    real = runner.run
    seen: dict[str, Any] = {"result": set(), "error": set(), "codes": {}}

    def fake(argv: Any, **kw: Any) -> Any:
        r = results[0]
        if isinstance(r, BaseException):
            raise r
        return r

    out, err = sys.stdout, sys.stderr
    try:
        runner.run = fake
        for label in ("a result", "a result", "run raised", "interrupted"):
            sys.stdout = io.TextIOWrapper(io.BytesIO(), encoding="utf-8")
            sys.stderr = io.StringIO()
            code = cli.main(["run", "--", "-c", "pass"])
            sys.stdout.flush()
            written = sys.stdout.buffer.getvalue().decode()
            if written:
                keys = set(json.loads(written))
                seen["result" if code == 0 else "error"] |= keys
            seen["codes"][code] = label
            results.pop(0)
        sys.stdout, sys.stderr = io.TextIOWrapper(io.BytesIO(), encoding="utf-8"), io.StringIO()
        seen["codes"][cli.main(["not-run"])] = "a usage error"
    finally:
        runner.run = real
        sys.stdout, sys.stderr = out, err
    entry = [k for k, v in scripts.items() if v.startswith("wasi_python")]
    return {
        "scripts": {k: scripts[k] for k in entry},
        "options": options,
        "result_keys": sorted(seen["result"]),
        "error_keys": sorted(seen["error"]),
        "codes": [[c, seen["codes"][c]] for c in sorted(seen["codes"])],
    }


