# Reading docstrings (Decision 9): only the object's own text, the same on every version.


def own_doc(obj: Any) -> str:
    """The object's own docstring, cleaned; "" when it has none of its own."""
    if isinstance(obj, property):
        raw = obj.fget.__doc__ if obj.fget is not None else None
    elif isinstance(obj, (staticmethod, classmethod)):
        raw = obj.__func__.__doc__
    elif inspect.isfunction(obj) or inspect.ismodule(obj):
        raw = obj.__doc__
    elif isinstance(obj, type):
        raw = vars(obj).get("__doc__")
        if raw and dataclasses.is_dataclass(obj) and raw.startswith(f"{obj.__name__}("):
            raw = None  # the text dataclasses generates is no documentation
    else:
        raw = None
    return inspect.cleandoc(raw or "")


def sections(doc: str) -> dict[str, dict[str, str]]:
    """Google-style sections: each heading's entries, by name, each text on one line. A heading
    starts at column 0; its entries share the first entry's indentation; deeper lines continue
    an entry; a line back at column 0 ends the section."""
    out: dict[str, dict[str, str]] = {}
    current: str | None = None
    entry: str | None = None
    indent: int | None = None
    for line in doc.splitlines():
        if not line.strip():
            continue
        if not line[0].isspace():
            m = _HEADING.match(line)
            current = {"Arguments": "Args"}.get(m.group(1), m.group(1)) if m else None
            if current is not None:
                out.setdefault(current, {})
            entry, indent = None, None
            continue
        if current is None:
            continue
        depth = len(line) - len(line.lstrip())
        indent = depth if indent is None else indent
        m = _ENTRY.match(line.strip())
        if depth == indent and m:
            entry = m.group(1)
            out[current][entry] = (m.group(2) or "").strip()
        elif entry is not None:
            out[current][entry] = (out[current][entry] + " " + line.strip()).strip()
    return out


def prose(doc: str) -> list[str]:
    """The paragraphs before the first section heading, each joined to one line."""
    paragraphs: list[str] = []
    block: list[str] = []
    for line in doc.splitlines():
        if _HEADING.match(line):
            break
        if line.strip():
            block.append(line.strip())
        elif block:
            paragraphs.append(" ".join(block))
            block = []
    if block:
        paragraphs.append(" ".join(block))
    return paragraphs


def summary(doc: str) -> str:
    paragraphs = prose(doc)
    return paragraphs[0] if paragraphs else ""


