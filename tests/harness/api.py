NEEDS_RAISES = ("run", "run_async", "artifacts", "artifact_dir", "set_defaults", "tool")
EXACT_RAISES = {"run": RUN_RAISES, "run_async": RUN_ASYNC_RAISES, "set_defaults": {"TypeError"}}


def _exempt(member: dict[str, Any], param: dict[str, Any]) -> bool:
    return member["name"] == "__call__" and param["kind"] in ("var-positional", "var-keyword")


def public_docstrings(inv: dict[str, Any]) -> list[tuple[str, str]]:
    """(where, text) for each public docstring: the two modules, each public name, and each
    public method and property."""
    out = []
    for modname, mod in inv.items():
        out.append((modname, mod["doc"]))
        for item in mod["items"]:
            if item["kind"] == "constant":
                continue
            out.append((f"{modname}.{item['name']}", item["doc"]))
            for m in item.get("members", []):
                out.append((f"{modname}.{item['name']}.{m['name']}", m["doc"]))
    return out


def doc_gaps(inv: dict[str, Any]) -> dict[str, list[str]]:
    """Every count of criterion 5, as the list of what is missing."""
    gaps: dict[str, list[str]] = {
        "docstrings": [],
        "method docstrings": [],
        "Args entries": [],
        "Attributes entries": [],
        "Raises": [],
        "shared arguments": [],
        "spec references": [],
    }
    for modname, mod in inv.items():
        if not mod["doc"]:
            gaps["docstrings"].append(modname)
        for item in mod["items"]:
            where = f"{modname}.{item['name']}"
            if item["kind"] == "constant":
                if f"`{item['name']}`" not in mod["doc"]:
                    gaps["docstrings"].append(f"{where} (named in no module docstring)")
                continue
            if not item["doc"]:
                gaps["docstrings"].append(where)
            secs = sections(item["doc"])
            for p in item.get("params", []):
                if p["name"] not in secs.get("Args", {}):
                    gaps["Args entries"].append(f"{where}: {p['name']}")
            for f in item.get("fields", []):
                if f["name"] not in secs.get("Attributes", {}):
                    gaps["Attributes entries"].append(f"{where}.{f['name']}")
            for m in item.get("members", []):
                mwhere = f"{where}.{m['name']}"
                if not m["doc"]:
                    gaps["method docstrings"].append(mwhere)
                margs = sections(m["doc"]).get("Args", {})
                for p in m["params"]:
                    if not _exempt(m, p) and p["name"] not in margs:
                        gaps["Args entries"].append(f"{mwhere}: {p['name']}")
            if item["name"] in NEEDS_RAISES and modname in PUBLIC:
                raises = secs.get("Raises")
                if not raises:
                    gaps["Raises"].append(f"{where}: no Raises section")
                elif item["name"] in EXACT_RAISES and set(raises) != EXACT_RAISES[item["name"]]:
                    want = EXACT_RAISES[item["name"]]
                    gaps["Raises"].append(
                        f"{where}: missing {sorted(want - set(raises))}, "
                        f"extra {sorted(set(raises) - want)}"
                    )
    top = {i["name"]: i for i in inv.get("wasi_python", {}).get("items", [])}
    if "run" in top and "run_async" in top:
        a = sections(top["run"]["doc"]).get("Args", {})
        b = sections(top["run_async"]["doc"]).get("Args", {})
        for p in top["run"]["params"]:
            if p["name"] in {q["name"] for q in top["run_async"]["params"]}:
                if a.get(p["name"]) != b.get(p["name"]):
                    gaps["shared arguments"].append(p["name"])
    for where, text in public_docstrings(inv):
        for m in _SPEC.finditer(text):
            gaps["spec references"].append(f"{where}: {m.group(0)!r}")
    return gaps


