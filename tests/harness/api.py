def _param_line(p: dict[str, Any], depth: int) -> str:
    star = {"var-positional": "*", "var-keyword": "**"}.get(p["kind"], "")
    text = " " * depth + f"param {star}{p['name']}"
    if p["annotation"] is not None:
        text += f": {p['annotation']}"
    if p["default"] is not None:
        text += f" = {p['default']}"
    return text + f"  {p['kind']}"


def _function_lines(f: dict[str, Any], depth: int) -> list[str]:
    pad = " " * depth
    lines = [f"{pad}{f['kind']} {f['name']} -> {f['returns']}"]
    lines += [_param_line(p, depth + 2) for p in f["params"]]
    for o in f["overloads"]:
        lines.append(f"{pad}  overload -> {o['returns']}")
        lines += [_param_line(p, depth + 4) for p in o["params"]]
    return lines


def _class_lines(c: dict[str, Any]) -> list[str]:
    bases = f"({', '.join(c['bases'])})" if c["bases"] else ""
    head = f"{c['kind']} {c['name']}{bases}"
    if c["kind"] == "dataclass":
        head += ": frozen" if c["frozen"] else ": not frozen"
        head += "".join(f", {p}" for p in c["options"])
    lines = [head]
    for f in c["fields"]:
        kw = "  kw_only" if f["kw_only"] else ""
        lines.append(f"  field {f['name']}: {f['annotation']} = {f['default']}{kw}")
    for name, value in c["enum"]:
        lines.append(f"  member {name} = {value}")
    for m in c["members"]:
        lines += _function_lines(m, 2)
    return lines


def snapshot_text(facts: dict[str, Any]) -> str:
    inv = facts["inventory"]
    lines: list[str] = []
    for modname in PUBLIC:
        lines.append(f"module {modname}")
        for item in inv[modname]["items"]:
            if item["kind"] == "constant":
                lines.append(f"constant {item['name']} = {item['value']}")
            elif item["kind"] in ("def", "async def"):
                lines += _function_lines(item, 0)
            else:
                lines += _class_lines(item)
        if modname == "wasi_python":
            lines += [f"default {k} = {v}" for k, v in facts["defaults"]]
            lines.append(f"stats keys: {' '.join(facts['stats_keys'])}")
            lines += [f"environment {name}" for name in facts["environment"]]
        else:
            lines.append(f"outcome kinds: {' '.join(facts['outcome_kinds'])}")
    cmd = facts["command"]
    for name, target in cmd["scripts"].items():
        lines.append(f"command {name} = {target}")
    for option, metavar, action in cmd["options"]:
        meta = f" {metavar}" if metavar else ""
        lines.append(f"  option {option}{meta}  {action}")
    lines.append("  exit codes: " + ", ".join(f"{c} {label}" for c, label in cmd["codes"]))
    lines.append(f"  json result: {' '.join(cmd['result_keys'])}")
    lines.append(f"  json error: {' '.join(cmd['error_keys'])}")
    return "\n".join(lines) + "\n"


def _signature(f: dict[str, Any], prefix: str = "") -> list[str]:
    """A function as Python source, one parameter per line when it has more than two."""
    parts = []
    params = f["params"]
    star_done = False
    for k, p in enumerate(params):
        if p["kind"] == "keyword-only" and not star_done:
            parts.append("*")
        if p["kind"] in ("keyword-only", "var-positional"):
            star_done = True
        star = {"var-positional": "*", "var-keyword": "**"}.get(p["kind"], "")
        text = f"{star}{p['name']}"
        if p["annotation"] is not None:
            text += f": {p['annotation']}"
        if p["default"] is not None:
            text += f" = {p['default']}"
        parts.append(text)
        last_positional = k + 1 == len(params) or params[k + 1]["kind"] != "positional-only"
        if p["kind"] == "positional-only" and last_positional:
            parts.append("/")
    keyword = "async def" if f["kind"] == "async def" else "def"
    ret = f" -> {f['returns']}" if f["returns"] is not None else ""
    if len(parts) <= 2:
        return [f"{prefix}{keyword} {f['name']}({', '.join(parts)}){ret}"]
    return (
        [f"{prefix}{keyword} {f['name']}("]
        + [f"{prefix}    {p}," for p in parts]
        + [f"{prefix}){ret}"]
    )


def _entries(title: str, entries: dict[str, str], names: list[str] | None = None) -> list[str]:
    keys = names if names is not None else list(entries)
    lines = [f"**{title}:**", ""]
    lines += [f"- `{k}`: {entries.get(k, '')}" for k in keys]
    return lines + [""]


def _reference_item(modname: str, item: dict[str, Any], mod_doc: str) -> list[str]:
    name = item["name"]
    lines = [f"#### `{modname}.{name}`", "", "```python"]
    if item["kind"] == "constant":
        lines += [f"{name} = {item['value']}", "```", ""]
        about = [p for p in prose(mod_doc) if f"`{name}`" in p]
        return lines + ([about[0], ""] if about else [])
    if item["kind"] in ("def", "async def"):
        lines += _signature(item)
        for o in item["overloads"]:
            lines += ["@overload"] + _signature({**o, "name": name, "kind": "def"})
    else:
        bases = f"({', '.join(item['bases'])})" if item["bases"] else ""
        if item["kind"] == "dataclass":
            extra = "".join(f", {p}" for p in item["options"])
            lines.append(f"@dataclass(frozen={item['frozen']}{extra})")
        lines.append(f"class {name}{bases}:")
        for f in item["fields"]:
            default = "" if f["default"] == "required" else f" = {f['default']}"
            note = "  # keyword-only" if f["kw_only"] else ""
            lines.append(f"    {f['name']}: {f['annotation']}{default}{note}")
        for member, value in item["enum"]:
            lines.append(f"    {member} = {value}")
        for m in item["members"]:
            if m["kind"] == "property":
                lines += ["    @property", f"    def {m['name']}(self) -> {m['returns']}"]
            elif m["kind"] == "classmethod":
                with_cls = {**m, "kind": "def", "params": [{"name": "cls", "kind": "positional",
                                                            "annotation": None, "default": None},
                                                           *m["params"]]}  # fmt: skip
                lines += ["    @classmethod", *_signature(with_cls, prefix="    ")]
            else:
                with_self = {**m, "params": [{"name": "self", "kind": "positional",
                                              "annotation": None, "default": None},
                                             *m["params"]]}  # fmt: skip
                lines += _signature(with_self, prefix="    ")
        if not (item["fields"] or item["enum"] or item["members"]):
            lines.append("    ...")
    lines += ["```", ""]
    doc = item["doc"]
    lines += [summary(doc), ""]
    secs = sections(doc)
    if name == "run_async" and modname == "wasi_python":
        lines += ["`run`'s arguments except `cancel`, plus:", ""]
        lines += [f"- `executor`: {secs.get('Args', {}).get('executor', '')}", ""]
    elif item.get("params"):
        lines += _entries("Args", secs.get("Args", {}), [p["name"] for p in item["params"]])
    if item.get("fields"):
        lines += _entries(
            "Attributes", secs.get("Attributes", {}), [f["name"] for f in item["fields"]]
        )
    if item.get("members"):
        lines += ["**Methods:**", ""]
    for m in item.get("members", []):
        msecs = sections(m["doc"]).get("Args", {})
        lines.append(f"- `{name}.{m['name']}`: {summary(m['doc'])}")
        lines += [
            f"  - `{p['name']}`: {msecs[p['name']]}" for p in m["params"] if p["name"] in msecs
        ]
    if item.get("members"):
        lines.append("")
    if secs.get("Raises"):
        lines += _entries("Raises", secs["Raises"])
    return lines


def reference_text(facts: dict[str, Any]) -> str:
    inv = facts["inventory"]
    lines: list[str] = []
    for modname in PUBLIC:
        lines += [f"### `{modname}`", ""]
        for item in inv[modname]["items"]:
            lines += _reference_item(modname, item, inv[modname]["doc"])
    cmd = facts["command"]
    lines += ["### The command", ""]
    for name in cmd["scripts"]:  # its entry point names an internal module: the snapshot's
        lines += [f"`{name} run [OPTIONS] [--] ARG...` (also `python -m wasi_python`):", ""]
    lines += ["| option | value | action |", "|---|---|---|"]
    for option, metavar, action in cmd["options"]:
        lines.append(f"| `{option}` | {f'`{metavar}`' if metavar else ''} | {action} |")
    lines += ["", "Exit codes: " + "; ".join(f"{c}, {label}" for c, label in cmd["codes"]) + "."]
    lines += [
        "",
        "One line of JSON: on a result, "
        + ", ".join(f"`{k}`" for k in cmd["result_keys"])
        + " (a stream that is not UTF-8 comes as its `_base64` key); on exit 1, "
        + ", ".join(f"`{k}`" for k in cmd["error_keys"])
        + ".",
    ]
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return "\n" + text.strip("\n") + "\n"


