# The child: everything the checks need from the live package, in one interpreter.


def _group(out: dict[str, Any], name: str, fn: Any) -> None:
    try:
        out[name] = fn()
    except Exception as e:  # noqa: BLE001  (one group's failure leaves the others' counts)
        out.setdefault("errors", {})[name] = f"{type(e).__name__}: {e}"


def child(package: Path) -> dict[str, Any]:
    import importlib

    sys.path.insert(0, str(package.parent))
    modules = {
        m: importlib.import_module(m)
        for m in (
            *PUBLIC,
            "wasi_python.runner",
            "wasi_python.cli",
            "wasi_python._artifacts",
            "wasi_python._engines",
        )
    }
    origin = Path(modules["wasi_python"].__file__).resolve().parent
    if origin != package.resolve():
        raise SystemExit(f"imported wasi_python from {origin}, not {package}")
    out: dict[str, Any] = {}
    _group(out, "inventory", lambda: inventory(modules))
    runner, cli, top = (
        modules["wasi_python.runner"],
        modules["wasi_python.cli"],
        modules["wasi_python"],
    )
    tools = modules["wasi_python.tools"]

    def star() -> dict[str, list[str]]:
        found = {}
        for m in PUBLIC:
            ns: dict[str, Any] = {}
            exec(f"from {m} import *", ns)  # noqa: S102
            found[m] = sorted(k for k in ns if k != "__builtins__")
        return found

    _group(out, "star", star)
    _group(
        out,
        "unresolved",
        lambda: [
            f"{m}.{n}"
            for m in PUBLIC
            for n in getattr(modules[m], "__all__", [])
            if not hasattr(modules[m], n)
        ],
    )

    def defaults() -> list[list[str]]:
        d = top.defaults()
        fields = dataclasses.fields(d)
        return [
            [
                f.name,
                "<factory>"
                if f.default_factory is not dataclasses.MISSING
                else repr(getattr(d, f.name)),
            ]
            for f in fields
        ]

    _group(out, "defaults", defaults)
    _group(out, "stats_keys", lambda: sorted(top.stats()))
    artifacts, engines = modules["wasi_python._artifacts"], modules["wasi_python._engines"]
    _group(out, "environment", lambda: sorted({artifacts._ARTIFACTS_ENV, engines.CACHE_ENV}))
    _group(out, "outcome_kinds", lambda: list(tools._KINDS))
    _group(out, "command", lambda: command_facts(cli, runner))
    if "inventory" in out:
        _group(
            out,
            "annotations",
            lambda: annotation_report(out["inventory"], annotation_namespace(modules)),
        )
    return out


@functools.cache
def _facts(package: str) -> str:
    r = subprocess.run(
        [sys.executable, "-I", str(Path(__file__).resolve()), "--child", "--package", package],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if r.returncode != 0:
        raise RuntimeError(
            f"the render's child failed ({r.returncode}): {r.stderr.strip()[-2000:]}"
        )
    return r.stdout


def facts(package: Path = PACKAGE) -> dict[str, Any]:
    """The child's facts for this package, read once per package per process."""
    return json.loads(_facts(str(Path(package).resolve())))


def render(package: Path = PACKAGE) -> tuple[str, str]:
    """(the snapshot, the reference page's block), or AssertionError naming what stopped the
    render."""
    errors = future_errors(package)
    f = facts(package)
    errors += [f"{k}: {v}" for k, v in f.get("errors", {}).items()]
    if errors:
        raise AssertionError("the render failed: " + "; ".join(errors))
    return snapshot_text(f), reference_text(f)


def diff(old: str, new: str, old_name: str, new_name: str) -> str:
    return "".join(
        difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True), old_name, new_name, n=1
        )
    )


def _write_text(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--child", action="store_true", help=argparse.SUPPRESS)
    p.add_argument("--package", type=Path, default=PACKAGE)
    p.add_argument("--snapshot", type=Path, default=SNAPSHOT)
    p.add_argument("--page", type=Path, default=PAGE)
    ns = p.parse_args(argv)
    if ns.child:
        sys.path[:] = [x for x in sys.path if Path(x or ".").resolve() != Path(__file__).parent]
        sys.stdout.write(json.dumps(child(ns.package), ensure_ascii=True))
        return 0
    snapshot, block = render(ns.package)
    page = ns.page.read_text(encoding="utf-8") if ns.page.is_file() else ""
    count, current = readme_block(page)
    if ns.write:
        _write_text(ns.snapshot, snapshot)
        if count != 1:
            print(f"{ns.page}: needs exactly one pair of markers ({BEGIN} … {END})")
            return 1
        before, rest = page.split(BEGIN, 1)
        _, after = rest.split(END, 1)
        body = "\n\n" + block.strip("\n") + "\n\n"
        _write_text(ns.page, before + BEGIN + body + END + after)
        return 0
    status = 0
    old = ns.snapshot.read_text(encoding="utf-8") if ns.snapshot.is_file() else ""
    if old != snapshot:
        print(diff(old, snapshot, str(ns.snapshot), "the live surface"), end="")
        status = 1
    if current is None or current.strip("\n") != block.strip("\n"):
        print(diff(current or "", block, f"{ns.page} (api reference)", "the live surface"), end="")
        status = 1
    if status:
        print(f"the public API differs from its snapshot or its page; if intended: {WRITE}")
    return status


if __name__ == "__main__":
    sys.exit(main())
