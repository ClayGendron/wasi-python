def _annotation(value: Any) -> str | None:
    if value is inspect.Parameter.empty:
        return None
    if not isinstance(value, str):
        raise AssertionError(f"annotation {value!r} is not a stored string")
    return value


def _params(fn: Any, *, skip_self: bool = False) -> list[dict[str, Any]]:
    out = []
    sig = inspect.signature(fn)
    for i, p in enumerate(sig.parameters.values()):
        if skip_self and i == 0 and p.name == "self":
            continue
        out.append(
            {
                "name": p.name,
                "kind": KINDS[p.kind],
                "annotation": _annotation(p.annotation),
                "default": None if p.default is inspect.Parameter.empty else repr(p.default),
            }
        )
    return out


def _returns(fn: Any) -> str | None:
    return _annotation(inspect.signature(fn).return_annotation)


def _bases(cls: type) -> list[str]:
    skip = {object, typing.Protocol, typing.Generic}
    return [b.__name__ for b in cls.__bases__ if b not in skip]


def _kind(obj: Any) -> str:
    if inspect.iscoroutinefunction(obj):
        return "async def"
    if inspect.isfunction(obj):
        return "def"
    if isinstance(obj, type):
        if dataclasses.is_dataclass(obj):
            return "dataclass"
        if getattr(obj, "_is_protocol", False):
            return "protocol"
        if issubclass(obj, enum.Enum):
            return "enum"
        if issubclass(obj, BaseException):
            return "exception"
        return "class"
    return "constant"


def _function(name: str, fn: Any, *, method: bool = False) -> dict[str, Any]:
    item = {
        "name": name,
        "kind": _kind(fn),
        "doc": own_doc(fn),
        "params": _params(fn, skip_self=method),
        "returns": _returns(fn),
        "overloads": [],
    }
    for o in typing.get_overloads(fn):
        item["overloads"].append({"params": _params(o), "returns": _returns(o)})
    return item


# The dunders a plain class's render records: its constructor and the context-manager pair
# (`Session`), beside `__call__`, which every class's records.
_PLAIN_DUNDERS = ("__init__", "__enter__", "__exit__")


def _members(cls: type) -> list[dict[str, Any]]:
    """Public methods and properties defined on the class itself, and `__call__`; for a plain
    class (not a dataclass, enum, protocol or exception), also `__init__` and the
    context-manager methods."""
    plain = _kind(cls) == "class"
    out = []
    for name, value in vars(cls).items():
        if name.startswith("_") and name != "__call__" and not (plain and name in _PLAIN_DUNDERS):
            continue
        if isinstance(value, property):
            out.append(
                {
                    "name": name,
                    "kind": "property",
                    "doc": own_doc(value),
                    "params": [],
                    "returns": _returns(value.fget),
                    "overloads": [],
                }
            )
        elif inspect.isfunction(value):
            out.append(_function(name, value, method=True))
        elif isinstance(value, classmethod):  # listed as one, without `cls`: called on the class
            item = _function(name, value.__func__, method=True)
            out.append({**item, "kind": "classmethod", "params": item["params"][1:]})
    return out


def _class(name: str, cls: type) -> dict[str, Any]:
    item: dict[str, Any] = {
        "name": name,
        "kind": _kind(cls),
        "doc": own_doc(cls),
        "bases": _bases(cls),
        "members": _members(cls),
        "fields": [],
        "frozen": None,
        "options": [],
        "enum": [],
    }
    if dataclasses.is_dataclass(cls):
        params = cls.__dataclass_params__
        item["frozen"] = params.frozen
        # Each other parameter that differs from dataclass()'s default: `Tool`'s eq=False is
        # its identity equality.
        item["options"] = [
            f"{k}={getattr(params, k)}"
            for k, default in (("init", True), ("repr", True), ("eq", True), ("order", False),
                               ("unsafe_hash", False))
            if getattr(params, k) != default
        ]  # fmt: skip
        for f in dataclasses.fields(cls):
            if f.name.startswith("_"):
                continue
            if f.default is not dataclasses.MISSING:
                default = repr(f.default)
            elif f.default_factory is not dataclasses.MISSING:
                default = "<factory>"
            else:
                default = "required"
            item["fields"].append(
                {
                    "name": f.name,
                    "annotation": _annotation(f.type),
                    "default": default,
                    "kw_only": bool(f.kw_only),
                }
            )
    if issubclass(cls, enum.Enum):
        item["enum"] = [[m.name, repr(m.value)] for m in cls]
    return item


def inventory(modules: dict[str, Any]) -> dict[str, Any]:
    """Each public module's `__all__`, its docstring, and each name's description."""
    out: dict[str, Any] = {}
    for modname in PUBLIC:
        mod = modules[modname]
        names = list(getattr(mod, "__all__", None) or [])
        items = []
        for name in names:
            obj = getattr(mod, name, None)
            if isinstance(obj, type):
                items.append(_class(name, obj))
            elif inspect.isfunction(obj):
                items.append(_function(name, obj))
            else:
                items.append({"name": name, "kind": "constant", "value": repr(obj), "doc": ""})
        out[modname] = {
            "all": names,
            "has_all": hasattr(mod, "__all__"),
            "doc": own_doc(mod),
            "items": items,
        }
    return out


