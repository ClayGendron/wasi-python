# Names by `ast`: what a module binds, what is internal (Decisions 4 and 10).


def _module_nodes(tree: ast.Module) -> list[ast.stmt]:
    """Module-level statements, inside module-level if/try/with blocks too, never in a def."""
    out: list[ast.stmt] = []
    todo = list(tree.body)
    while todo:
        node = todo.pop(0)
        out.append(node)
        if isinstance(node, (ast.If, ast.Try, ast.With)):
            for block in ("body", "orelse", "finalbody", "handlers"):
                for child in getattr(node, block, []):
                    todo += child.body if isinstance(child, ast.ExceptHandler) else [child]
    return out


def _targets(node: ast.AST) -> list[str]:
    if isinstance(node, ast.Name):
        return [node.id]
    if isinstance(node, (ast.Tuple, ast.List)):
        return [n for e in node.elts for n in _targets(e)]
    return []


def bindings(path: Path, *, imports: bool = True) -> list[tuple[str, str]]:
    """(name, how) for every module-level binding: "def", "class", "assign" (`X = …`), "unpack"
    (`X, Y = …`), or "import" for an import from inside the package; imports from outside it are
    left out."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    out: list[tuple[str, str]] = []
    for node in _module_nodes(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append((node.name, "def"))
        elif isinstance(node, ast.ClassDef):
            out.append((node.name, "class"))
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                how = "assign" if isinstance(t, ast.Name) else "unpack"
                out += [(n, how) for n in _targets(t)]
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            out += [(n, "assign") for n in _targets(node.target)]
        elif imports and isinstance(node, ast.ImportFrom):
            inside = node.level > 0 or (node.module or "").split(".")[0] == "wasi_python"
            if inside:
                out += [(a.asname or a.name, "import") for a in node.names]
    return out


def declared_all(path: Path) -> list[str] | None:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in _module_nodes(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
        ):
            return list(ast.literal_eval(node.value))
    return None


def private_name_errors(package: Path = PACKAGE) -> list[str]:
    """Criterion 3: every name a public module binds and does not export starts with `_`."""
    errors = []
    for modname, filename in PUBLIC_FILES.items():
        exported = set(declared_all(package / filename) or [])
        for name, how in bindings(package / filename):
            dunder = name.startswith("__") and name.endswith("__")
            if not dunder and not name.startswith("_") and name not in exported:
                errors.append(f"{modname}.{name} ({how})")
    return errors


def reexport_errors(package: Path = PACKAGE) -> list[str]:
    """Criterion 4: no name in a public `__all__` is bound from a name starting with `_`."""
    errors = []
    for modname, filename in PUBLIC_FILES.items():
        path = package / filename
        exported = set(declared_all(path) or [])
        for node in _module_nodes(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom):
                for a in node.names:
                    if (a.asname or a.name) in exported and a.name.startswith("_"):
                        errors.append(f"{modname}.{a.asname or a.name} is {a.name}")
            elif isinstance(node, ast.Assign) and isinstance(node.value, (ast.Name, ast.Attribute)):
                source = node.value.id if isinstance(node.value, ast.Name) else node.value.attr
                for t in node.targets:
                    for name in _targets(t):
                        if name in exported and source.startswith("_"):
                            errors.append(f"{modname}.{name} is {source}")
    return errors


def future_errors(package: Path = PACKAGE) -> list[str]:
    """Each module defining a public name stores its annotations as strings."""
    errors = []
    for filename in DEFINING:
        tree = ast.parse((package / filename).read_text(encoding="utf-8"))
        if not any(
            isinstance(n, ast.ImportFrom)
            and n.module == "__future__"
            and any(a.name == "annotations" for a in n.names)
            for n in tree.body
        ):
            errors.append(f"{filename} lacks `from __future__ import annotations`")
    return errors


def internal_names(package: Path = PACKAGE) -> set[str]:
    """Names an internal module defines at module level: a def, a class, or a plain assignment
    (`X = …`). Names unpacked together (`EBADF, EIO = 8, 29`) are preview1's own numbers, the
    words a document uses for them; Errno's member names are public through `Errno`; and a
    dunder such as `__all__` belongs to every module."""
    found = {
        name
        for filename in INTERNAL_FILES
        if (package / filename).is_file()
        for name, how in bindings(package / filename, imports=False)
        if how != "unpack" and not (name.startswith("__") and name.endswith("__"))
    }
    return found - errno_members(package)


def errno_members(package: Path = PACKAGE) -> set[str]:
    tree = ast.parse((package / "mounts.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "Errno":
            return {
                n for s in node.body if isinstance(s, ast.Assign) for n in _targets(s.targets[0])
            }
    return set()


def internal_constants(package: Path = PACKAGE) -> set[str]:
    """Upper-case constants an internal module assigns at module level, Errno's names left out
    (they are public through `Errno`)."""
    found = set()
    for filename in INTERNAL_FILES:
        if (package / filename).is_file():
            for name, how in bindings(package / filename, imports=False):
                if how == "assign" and _CONSTANT.match(name):
                    found.add(name)
    return found - errno_members(package)


def public_names(inv: dict[str, Any]) -> set[str]:
    return {n for mod in inv.values() for n in mod["all"]}


def _run(text: str, at: int) -> int:
    """The length of the run of backticks starting at `at`."""
    end = at
    while end < len(text) and text[end] == "`":
        end += 1
    return end - at


def code_spans(text: str) -> list[tuple[int, str]]:
    """Markdown code spans as (line, content): a run of n backticks closes at the next run of
    exactly n; a run with no closer is text. Content may wrap a line."""
    out = []
    i = 0
    while (start := text.find("`", i)) >= 0:
        n = _run(text, start)
        j = start + n
        i = j  # no closer: the run is text
        while (close := text.find("`", j)) >= 0:
            m = _run(text, close)
            if m == n:
                out.append((text.count("\n", 0, start) + 1, text[start + n : close]))
                i = close + n
                break
            j = close + m
    return out


_FENCE = re.compile(r"[ \t]*(`{3,}|~{3,})")


def fenced(text: str) -> tuple[str, list[tuple[int, str]]]:
    """The text with every fenced block blanked (newlines kept, so line numbers hold), and each
    block's lines as (line, text). A fence may be indented; it closes on a line of the same
    character, at least as long."""
    lines = text.split("\n")
    blocks: list[tuple[int, str]] = []
    out = []
    fence: str | None = None
    for number, line in enumerate(lines, 1):
        m = _FENCE.match(line)
        if fence is None:
            if m:
                fence = m.group(1)
                out.append("")
                continue
            out.append(line)
        else:
            if (
                m
                and m.group(1)[0] == fence[0]
                and len(m.group(1)) >= len(fence)
                and not line[m.end() :].strip()
            ):
                fence = None
            else:
                blocks.append((number, line))
            out.append("")
    return "\n".join(out), blocks


def _holds(text: str, names: set[str]) -> list[str]:
    found = [m for m in INTERNAL_MODULES if re.search(rf"\b{re.escape(m)}\b", text)]
    words = set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text))
    return found + sorted(words & names)


def readme_hits(text: str, constants: set[str], name: str = "README.md") -> list[str]:
    """Criterion 6's rule for a public page (`name`, the README by default): spans and fenced
    lines that name an internal module or an internal module's upper-case constant. Fences are
    blanked first, then searched."""
    plain, blocks = fenced(text)
    hits = []
    for line, span in code_spans(plain):
        names = _holds(span, constants)
        if names:
            hits.append(f"{name}:{line} `{' '.join(span.split())}` ({', '.join(names)})")
    for line, code in blocks:
        names = _holds(code, constants)
        if names:
            hits.append(f"{name}:{line} (fenced) {code.strip()} ({', '.join(names)})")
    return hits


def docstring_hits(inv: dict[str, Any], internal: set[str]) -> list[str]:
    """Criterion 6's docstring rule: a backticked token whose root an internal module defines
    and that is not a public name, or a span naming an internal module."""
    allowed = public_names(inv)
    hits = []
    for where, text in public_docstrings(inv):
        for _, span in code_spans(text):
            roots = {t.split(".")[0] for t in _IDENT.findall(span)}
            bad = sorted((roots & internal) - allowed)
            bad += [m for m in INTERNAL_MODULES if re.search(rf"\b{re.escape(m)}\b", span)]
            if bad:
                hits.append(f"{where}: `{' '.join(span.split())}` ({', '.join(bad)})")
    return hits


def readme_block(text: str) -> tuple[int, str | None]:
    """(how many blocks, the one block's content) between the markers, fences ignored."""
    plain, _ = fenced(text)
    lines = plain.split("\n")
    begins = [i for i, line in enumerate(lines) if line.strip() == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == END]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        return max(len(begins), len(ends)), None
    original = text.split("\n")
    return 1, "\n".join(original[begins[0] + 1 : ends[0]])


