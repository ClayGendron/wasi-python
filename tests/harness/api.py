# Annotations (Decision 12): each evaluates in a namespace of public and standard names.


def annotation_namespace(modules: dict[str, Any]) -> dict[str, Any]:
    import asyncio
    import builtins
    import collections.abc
    import concurrent.futures
    import os
    import pathlib
    import threading

    ns: dict[str, Any] = dict(vars(builtins))
    ns.update({k: v for k, v in vars(typing).items() if not k.startswith("_")})
    ns.update({k: v for k, v in vars(collections.abc).items() if not k.startswith("_")})
    ns.update(os=os, threading=threading, concurrent=concurrent, Path=pathlib.Path)
    ns.update(asyncio=asyncio)
    assert concurrent.futures
    for modname in PUBLIC:
        mod = modules[modname]
        ns.update({n: getattr(mod, n) for n in getattr(mod, "__all__", []) if hasattr(mod, n)})
    return ns


def annotation_report(inv: dict[str, Any], ns: dict[str, Any]) -> dict[str, Any]:
    evaluated = 0
    failed: list[str] = []

    def one(where: str, text: str | None) -> None:
        nonlocal evaluated
        if text is None:
            failed.append(f"{where}: not annotated")
            return
        evaluated += 1
        try:
            eval(text, dict(ns))  # noqa: S307  (the package's own annotation strings)
        except Exception as e:  # noqa: BLE001
            failed.append(f"{where}: {text} ({type(e).__name__}: {e})")

    def function(where: str, f: dict[str, Any], method: bool = False) -> None:
        for p in f["params"]:
            if not (method and _exempt(f, p) and p["annotation"] is None):
                one(f"{where}({p['name']})", p["annotation"])
        if f["kind"] != "property" or f["returns"] is not None:
            one(f"{where} return", f["returns"])
        for k, o in enumerate(f["overloads"], 1):
            for p in o["params"]:
                one(f"{where} overload {k}({p['name']})", p["annotation"])
            one(f"{where} overload {k} return", o["returns"])

    for modname, mod in inv.items():
        for item in mod["items"]:
            where = f"{modname}.{item['name']}"
            if item["kind"] in ("def", "async def"):
                function(where, item)
            for f in item.get("fields", []):
                one(f"{where}.{f['name']}", f["annotation"])
            for m in item.get("members", []):
                function(f"{where}.{m['name']}", m, method=True)
    return {"evaluated": evaluated, "failed": failed}


