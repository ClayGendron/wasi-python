"""Compile a recipe module at build time.

    PYTHONHASHSEED=0 freeze_bootstrap.py <src.py> <out.h> [<NAME> <filename>]

Writes a C header holding the module's marshalled code object as `static const unsigned char
<NAME>[]`, and its bytecode magic as `<NAME>_MAGIC`, which recipes/reactor_main.c checks before it
loads the code, so no start of the plain reactor compiles Python source. The code object's file
name is `<filename>`. The defaults, `REACTOR_BOOTSTRAP` and `<reactor>`, give the reactor's own
bootstrap (`_reactor`, from recipes/reactor_bootstrap.py); step 60 also freezes
recipes/zip_directory.py and recipes/zip_resources.py as `<frozen _zip_directory>` and
`<frozen _zip_resources>`, the way CPython names its own frozen modules.

The host Python is the guest's own version (scripts/line.conf): marshal's format and the bytecode
are the same, and the header carries the bytecode magic the reactor checks. Run with
PYTHONHASHSEED=0: set constants are marshalled in hash order. `compile_module` and `render` sit
outside that gate, so the judge's host can check them on its own Python.
"""

from __future__ import annotations

import importlib.util
import marshal
import os
import sys
from pathlib import Path

import line

TARGET = line.target()
DEFAULT_NAME = "REACTOR_BOOTSTRAP"
DEFAULT_FILENAME = "<reactor>"


def compile_module(source: str, filename: str) -> bytes:
    """The module's code object, compiled under `filename` and marshalled."""
    code = compile(source, filename, "exec", dont_inherit=True, optimize=0)
    return marshal.dumps(code)


def render(data: bytes, magic: int, name: str = DEFAULT_NAME, source: str = "") -> str:
    """The header text: a comment naming `source`, `<name>_MAGIC` and `<name>[]`, 24 bytes a row."""
    rows = [", ".join(str(b) for b in data[i : i + 24]) for i in range(0, len(data), 24)]
    return (
        f"/* Generated by scripts/freeze_bootstrap.py from {source}: do not edit. */\n"
        f"#define {name}_MAGIC {magic}L\n"
        f"static const unsigned char {name}[] = {{\n"
        + "".join(f"    {row},\n" for row in rows)
        + "};\n"
    )


def main() -> int:
    args = sys.argv[1:]
    if len(args) not in (2, 4):
        raise SystemExit("usage: freeze_bootstrap.py <src.py> <out.h> [<NAME> <filename>]")
    src, out = Path(args[0]), Path(args[1])
    name, filename = args[2:4] if len(args) == 4 else (DEFAULT_NAME, DEFAULT_FILENAME)
    if sys.version_info[:2] != TARGET:
        raise SystemExit(f"needs Python {TARGET[0]}.{TARGET[1]}, the guest's version")
    if os.environ.get("PYTHONHASHSEED") != "0":
        raise SystemExit("run with PYTHONHASHSEED=0, so the marshalled bytes repeat")
    data = compile_module(src.read_text(), filename)
    magic = int.from_bytes(importlib.util.MAGIC_NUMBER, "little")
    out.write_text(render(data, magic, name, src.name))
    print(f"{out.name}: {len(data)} bytes of marshalled code")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
