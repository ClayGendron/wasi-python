"""Compile the reactor's bootstrap at build time (spec 003, Decision 6).

    PYTHONHASHSEED=0 freeze_bootstrap.py <recipes/reactor_bootstrap.py> <out.h>

Writes a C header holding the module's marshalled code object, which recipes/reactor_main.c loads
with PyMarshal_ReadObjectFromString, so no start of the plain reactor compiles Python source. The
host Python is the guest's own version (scripts/line.conf): marshal's format and the bytecode are the same, and
the header carries the bytecode magic the reactor checks before it loads. Run with
PYTHONHASHSEED=0: set constants are marshalled in hash order.
"""

from __future__ import annotations

import importlib.util
import marshal
import os
import sys
from pathlib import Path

import line

TARGET = line.target()


def main() -> int:
    src, out = (Path(p) for p in sys.argv[1:3])
    if sys.version_info[:2] != TARGET:
        raise SystemExit(f"needs Python {TARGET[0]}.{TARGET[1]}, the guest's version")
    if os.environ.get("PYTHONHASHSEED") != "0":
        raise SystemExit("run with PYTHONHASHSEED=0, so the marshalled bytes repeat")
    code = compile(src.read_text(), "<reactor>", "exec", dont_inherit=True, optimize=0)
    data = marshal.dumps(code)
    magic = int.from_bytes(importlib.util.MAGIC_NUMBER, "little")
    rows = [", ".join(str(b) for b in data[i : i + 24]) for i in range(0, len(data), 24)]
    out.write_text(
        f"/* Generated by scripts/freeze_bootstrap.py from {src.name}: do not edit. */\n"
        f"#define REACTOR_BOOTSTRAP_MAGIC {magic}L\n"
        "static const unsigned char REACTOR_BOOTSTRAP[] = {\n"
        + "".join(f"    {row},\n" for row in rows)
        + "};\n"
    )
    print(f"{out.name}: {len(data)} bytes of marshalled code")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
