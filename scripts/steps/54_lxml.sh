#!/bin/sh
# Step 54: lxml 6.1.3's two C extension modules, lxml.etree and lxml.objectify, for wasm32-wasip1.
# The sdist ships the C that Cython 3.2.9 generated from them, so a build
# needs no Cython (lxml's setupinfo.py uses it when Cython is absent); it is compiled here, as step
# 35 compiles SQLite's amalgamation, with lxml's own macros for a static build. Each module becomes
# a static archive beside a .deps file, written by scripts/wasi-cc at its import path under
# build/lxml-build/ for step 60, as numpy's and pandas' are. The package's Python files go under
# build/lxml-install/ for step 70, without lxml.isoschematron (Decision 8). lxml's five
# Cython-compiled Python modules stay plain Python (Decision 1). Needs steps 10, 20 and 36.
set -eu
. "$(dirname "$0")/common.sh"

for lib in libxml2.a libxslt.a libexslt.a; do
  [ -s "$B/xml-libs/lib/$lib" ] || die "build/xml-libs/lib/$lib is missing: run step 36"
done
[ -f "$W/pyconfig.h" ] || die "no WASI pyconfig.h at $W: run step 20"
LXML_TGZ=$(pinned lxml-6.1.3.tar.gz)
L="$B/lxml-6.1.3"
OBJ="$B/lxml-build"
INST="$B/lxml-install"
SUFFIX=".cpython-$PYTHON_TAG-wasm32-wasi.so"
remove "$L" "$OBJ" "$INST"
mkdir -p "$OBJ/lxml" "$INST"
tar -xzf "$LXML_TGZ" -C "$B"
[ -d "$L" ] || die "the pinned tarball did not unpack to build/lxml-6.1.3"
patch_tree "$L"
LXML_VERSION=$(sed -n 's/^Version: //p' "$L/PKG-INFO" | head -n 1)
[ "$LXML_VERSION" = 6.1.3 ] || die "lxml's PKG-INFO says version $LXML_VERSION"
# A later sdist with other generated code is a visible change, not a silent one.
for m in etree objectify; do
  [ "$(head -n 1 "$L/src/lxml/$m.c")" = "/* Generated by Cython 3.2.9 */" ] \
    || die "src/lxml/$m.c is not Cython 3.2.9's generated C"
done

# lxml's setupinfo.define_macros() for a static libxml2 and libxslt, the line's WASI emulation
# defines, -DNDEBUG and the prefix map (no build path in the binary).
XML="$B/xml-libs"
CFLAGS="-O2 -DNDEBUG -ffile-prefix-map=$HERE=/wasi-python-build -DLIBXML_STATIC -DLIBXSLT_STATIC
  -DLIBEXSLT_STATIC -DCYTHON_CLINE_IN_TRACEBACK=0 -D_WASI_EMULATED_SIGNAL
  -D_WASI_EMULATED_PROCESS_CLOCKS -D_WASI_EMULATED_GETPID -I$L/src/lxml -I$L/src/lxml/includes
  -I$CP/Include -I$W -I$XML/include/libxml2 -I$XML/include"
for m in etree objectify; do
  "$HERE/scripts/wasi-cc" $CFLAGS -c "$L/src/lxml/$m.c" -o "$OBJ/$m.o" > "$OBJ/$m.log" 2>&1 \
    || { tail -n 20 "$OBJ/$m.log"; die "lxml's $m.c did not compile (build/lxml-build/$m.log)"; }
  echo "$m.c: $(grep -c 'warning:' "$OBJ/$m.log" || :) warnings (build/lxml-build/$m.log)"
done
"$HERE/scripts/wasi-cc" -shared -o "$OBJ/lxml/etree$SUFFIX" "$OBJ/etree.o" \
  "$XML/lib/libexslt.a" "$XML/lib/libxslt.a" "$XML/lib/libxml2.a"
"$HERE/scripts/wasi-cc" -shared -o "$OBJ/lxml/objectify$SUFFIX" "$OBJ/objectify.o"
for m in etree objectify; do
  [ -s "$OBJ/lxml/$m$SUFFIX" ] || die "step 54 made no lxml/$m$SUFFIX"
done

# The package, without isoschematron; step 70's suffix rules leave the C, headers, Cython
# sources and tests out of the zip.
cp -R "$L/src/lxml" "$INST/lxml"
remove "$INST/lxml/isoschematron"
n=$(find "$INST/lxml" -name '*.py' -not -path '*/tests/*' | wc -l | tr -d ' ')
echo "lxml: 2 extension archives under build/lxml-build; $n Python modules under build/lxml-install"
