"""Write one C file that calls, directly, every routine f2py's generated modules call through a
function pointer (spec 037, Decision 6: the direct-call gate).

    f2py_direct_calls.py <out.c> <module.c>...

f2py keeps each Fortran routine's address in a table and calls it through a pointer, so a routine
whose signature differs from the one f2py declared links silently and traps at run time. This file
makes wasm-ld's signature check see every one: it is the first module's own preamble (its includes,
typedefs and F_FUNC macros, up to its first `extern ... F_FUNC(...)` prototype), every module's
prototypes, and one function, `wasi_scipy_direct_calls`, with one call per routine, each argument a
literal 0. Step 57 compiles it with _flapackmodule.c's own flags (so the same rename headers
apply) and links it with what the modules link; a `signature mismatch` or an undefined symbol stops
the build. Two modules that declare one routine differently stop it here.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PROTOTYPE = re.compile(r"^extern\s+(.+?)\s+(F_FUNC(?:_US)?)\((\w+),(\w+)\)\((.*)\);\s*$", re.M)


def arity(args: str) -> int:
    """How many parameters a prototype's parameter list has (commas at depth 0, plus one)."""
    if args.strip() in ("", "void"):
        return 0
    depth, n = 0, 1
    for ch in args:
        depth += ch == "("
        depth -= ch == ")"
        n += ch == "," and depth == 0
    return n


def render(modules: list[tuple[str, str]]) -> tuple[str, int]:
    """(the C file, the number of routines) for [(module name, module text), ...]."""
    first = modules[0][1]
    m = PROTOTYPE.search(first)
    if m is None:
        raise SystemExit(f"{modules[0][0]}: no `extern ... F_FUNC(...)` prototype")
    preamble = first[: m.start()]
    seen: dict[str, tuple[str, str]] = {}
    protos, calls = [], []
    for name, text in modules:
        for p in PROTOTYPE.finditer(text):
            ret, macro, low, up, args = p.groups()
            line = p.group(0).strip()
            if low in seen:
                if seen[low][1] != line:
                    raise SystemExit(f"{low}: {seen[low][0]} and {name} declare it differently")
                continue
            seen[low] = (name, line)
            protos.append(line)
            zeros = ", ".join(["0"] * arity(args))
            calls.append(f"    (void){macro}({low},{up})({zeros});")
    if not calls:
        raise SystemExit("no routine found")
    body = "\n".join(protos)
    func = "void wasi_scipy_direct_calls(void)\n{\n" + "\n".join(calls) + "\n}\n"
    head = "/* Generated by scripts/f2py_direct_calls.py: one direct call per f2py routine. */\n"
    return head + preamble + body + "\n\n" + func, len(calls)


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: f2py_direct_calls.py <out.c> <module.c>...", file=sys.stderr)
        return 2
    out, sources = Path(argv[0]), [Path(a) for a in argv[1:]]
    text, n = render([(s.name, s.read_text(encoding="utf-8")) for s in sources])
    out.write_text(text, encoding="utf-8")
    print(f"{out.name}: {n} routines from {', '.join(s.name for s in sources)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
